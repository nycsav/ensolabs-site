#!/usr/bin/env node
/**
 * linkedin-checklist.js
 * Enso Labs — LinkedIn Publish Automation Helper
 *
 * Usage: node scripts/linkedin-checklist.js <slug> <article-url> [post-date]
 *
 * What it does:
 *   1. Generates organic + paid UTM links
 *   2. Writes UTM links back into content/linkedin/<slug>/LINKEDIN-POST.md
 *   3. Appends a new entry to content/PERFORMANCE-LOG.md
 *   4. Prints a summary to stdout
 *
 * Called by the /linkedin-post Claude Code slash command.
 */

const fs = require('fs');
const path = require('path');

// ── Args ──────────────────────────────────────────────────────────────────────
const [, , slug, articleUrl, postDate] = process.argv;

if (!slug || !articleUrl) {
  console.error('Usage: node scripts/linkedin-checklist.js <slug> <article-url> [YYYY-MM-DD]');
  process.exit(1);
}

const today = postDate || new Date().toISOString().slice(0, 10);
const campaignName = slug; // slug IS the campaign name

// ── UTM generation ────────────────────────────────────────────────────────────
const baseUrl = articleUrl.split('?')[0]; // strip any existing params

const utmOrganic = `${baseUrl}?utm_source=linkedin&utm_medium=organic&utm_campaign=${campaignName}&utm_content=carousel`;
const utmPaid    = `${baseUrl}?utm_source=linkedin&utm_medium=paid-social&utm_campaign=${campaignName}-boost&utm_content=carousel`;

// ── Update LINKEDIN-POST.md ───────────────────────────────────────────────────
const postFilePath = path.join(
  __dirname, '..', 'content', 'linkedin', slug, 'LINKEDIN-POST.md'
);

if (fs.existsSync(postFilePath)) {
  let postContent = fs.readFileSync(postFilePath, 'utf8');

  const utmBlock = `## Tracked links (auto-generated ${today})

**Organic post** *(paste this in the post body — never in comments)*
\`\`\`
${utmOrganic}
\`\`\`

**Boosted post** *(use this when setting up Campaign Manager boost)*
\`\`\`
${utmPaid}
\`\`\`

`;

  // Replace existing tracked links block if present, otherwise prepend
  if (postContent.includes('## Tracked links')) {
    postContent = postContent.replace(
      /## Tracked links[\s\S]*?(?=\n## |\n---|\n# |$)/,
      utmBlock
    );
  } else {
    postContent = utmBlock + postContent;
  }

  fs.writeFileSync(postFilePath, postContent, 'utf8');
  console.log(`✓ UTM links written to ${postFilePath}`);
} else {
  console.warn(`⚠ LINKEDIN-POST.md not found at ${postFilePath} — skipping write`);
}

// ── Append to PERFORMANCE-LOG.md ──────────────────────────────────────────────
const logPath = path.join(__dirname, '..', 'content', 'PERFORMANCE-LOG.md');

// 7 days from today
const boostDate = new Date(today);
boostDate.setDate(boostDate.getDate() + 7);
const boostDateStr = boostDate.toISOString().slice(0, 10);

const logEntry = `
---

## ${slug} — Posted ${today}

| Field | Value |
|---|---|
| Slug | \`${slug}\` |
| Article URL | ${baseUrl} |
| Post date | ${today} |
| OG pre-warm | ☐ LinkedIn Post Inspector run |
| Calendar: 24h check | ${today} +1 day @ 9am ET |
| Calendar: 7d boost review | ${boostDateStr} @ 9am ET |

### UTM links
- **Organic:** \`${utmOrganic}\`
- **Paid:** \`${utmPaid}\`

### Boost audience spec
- Seniority: Director, VP, C-Suite, Partner, Owner
- Company size: 201–5,000 employees
- Industries: Financial Services, Pharmaceuticals, Manufacturing, Retail, Consumer Goods, Technology
- Exclude: Advertising Services / Marketing & Advertising (1–50 employees)
- Geography: United States
- Budget: $50–75 / 7 days
- Objective: Engagement
- Campaign Manager account ID: 510047438

### Performance (fill in at 24h and 7d)

| Metric | 24h | 7d |
|---|---|---|
| Impressions | | |
| Reactions | | |
| Comments | | |
| Reposts | | |
| Profile views from post | | |
| Followers gained | | |
| GA4 sessions (UTM) | | |
| Boosted? | | Y/N + spend |

### Notes
_Add targeting learnings, content observations, and boost decision here._

`;

// Ensure the log file exists with a header
if (!fs.existsSync(logPath)) {
  fs.writeFileSync(logPath, `# LinkedIn Performance Log\n\nEnso Labs — Strategy → Ship content performance tracking.\nGenerated by \`scripts/linkedin-checklist.js\`.\n`, 'utf8');
}

fs.appendFileSync(logPath, logEntry, 'utf8');
console.log(`✓ Performance log entry appended to ${logPath}`);

// ── Summary ───────────────────────────────────────────────────────────────────
console.log(`
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
  LinkedIn Checklist — ${slug} — ${today}
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

  Organic UTM:
  ${utmOrganic}

  Boost UTM:
  ${utmPaid}

  Boost date:   ${boostDateStr}
  Log:          content/PERFORMANCE-LOG.md

  Next steps:
  1. Run Post Inspector → confirm OG image
  2. Check calendar holds were created (24h + 7d)
  3. Post carousel to LinkedIn — paste ORGANIC UTM in post body
  4. On ${boostDateStr}: open Campaign Manager, use audience spec in log
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
`);
